/**
 * What prebuild generates must still carry the native facts that have bitten.
 *
 * `ios/` is generated (Continuous Native Generation): it is gitignored, EAS
 * runs `expo prebuild` on its own servers, and app.json plus `plugins/` are the
 * whole source of truth. That makes the old failure mode, a committed native
 * project silently disagreeing with app.json, impossible. What is left to guard
 * is the config itself, so this runs a real prebuild into a throwaway
 * directory and checks the output:
 *
 * - Push entitlements per build configuration. Debug asks for the development
 *   APNs gateway and Release for production. A store build that asks for
 *   development registers sandbox tokens and every notification silently
 *   fails. `plugins/withReleasePushEntitlements.cjs` owns the Release file.
 * - Sign in with Apple and the associated domains, in both files.
 * - The privacy manifest, from `ios.privacyManifests`.
 * - The app icon, from `icon`.
 * - That `ios/` has not crept back into git, which is how every one of these
 *   used to drift.
 *
 * Run from apps/mobile:
 *   node scripts/check-native-assets.mjs
 */
import { execFileSync } from 'node:child_process';
import { cp, mkdtemp, readFile, rm, symlink } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';

const APP_ROOT = path.resolve(import.meta.dirname, '..');
const problems = [];

const tracked = execFileSync('git', ['ls-files', 'ios'], {
  cwd: APP_ROOT,
  encoding: 'utf8',
}).trim();
if (tracked) {
  problems.push(
    'ios/ is tracked in git again. It is generated by `expo prebuild`; ' +
      'move any hand edit into app.json or plugins/ and untrack it with ' +
      '`git rm -r --cached apps/mobile/ios`.',
  );
}

const { expo } = JSON.parse(
  await readFile(path.join(APP_ROOT, 'app.json'), 'utf8'),
);

// Prebuild into a copy, never into the working tree: a local ios/ may hold a
// Pods install and build products someone is using.
const workDir = await mkdtemp(path.join(os.tmpdir(), 'gpp-prebuild-'));
try {
  for (const entry of [
    'app.json',
    'package.json',
    'index.js',
    'assets',
    'plugins',
  ]) {
    await cp(path.join(APP_ROOT, entry), path.join(workDir, entry), {
      recursive: true,
    });
  }
  await symlink(
    path.join(APP_ROOT, 'node_modules'),
    path.join(workDir, 'node_modules'),
  );
  execFileSync(
    'npx',
    ['expo', 'prebuild', '--platform', 'ios', '--no-install'],
    { cwd: workDir, env: { ...process.env, CI: '1' }, stdio: 'pipe' },
  );

  const ios = path.join(workDir, 'ios');
  function read(relative) {
    return readFile(path.join(ios, relative), 'utf8').catch(() => null);
  }
  const pbxproj =
    (await read('GrandPrixPicks.xcodeproj/project.pbxproj')) ?? '';

  const ENTITLEMENTS = [
    {
      config: 'Debug',
      file: 'GrandPrixPicks.entitlements',
      aps: 'development',
    },
    {
      config: 'Release',
      file: 'GrandPrixPicksRelease.entitlements',
      aps: 'production',
    },
  ];
  for (const { config, file, aps } of ENTITLEMENTS) {
    const raw = await read(`GrandPrixPicks/${file}`);
    if (raw === null) {
      problems.push(`${config}: prebuild did not generate ${file}`);
      continue;
    }
    const actual = /<key>aps-environment<\/key>\s*<string>(.*?)<\/string>/.exec(
      raw,
    )?.[1];
    if (actual !== aps) {
      problems.push(
        `${config}: ${file} has aps-environment ${JSON.stringify(actual)}, expected ${JSON.stringify(aps)}. ` +
          'A Release build asking for development registers sandbox push tokens, and every notification silently fails.',
      );
    }
    if (!pbxproj.includes(`CODE_SIGN_ENTITLEMENTS = GrandPrixPicks/${file};`)) {
      problems.push(`${config}: project.pbxproj does not sign with ${file}`);
    }
    for (const domain of expo.ios?.associatedDomains ?? []) {
      if (!raw.includes(`<string>${domain}</string>`)) {
        problems.push(
          `${config}: ${file} is missing associated domain ${domain}`,
        );
      }
    }
    if (
      expo.ios?.usesAppleSignIn &&
      !raw.includes('com.apple.developer.applesignin')
    ) {
      problems.push(`${config}: ${file} is missing Sign in with Apple`);
    }
  }

  if (
    (await read('GrandPrixPicks/PrivacyInfo.xcprivacy')) === null ||
    !pbxproj.includes('PrivacyInfo.xcprivacy in Resources')
  ) {
    problems.push(
      'Prebuild did not generate and bundle PrivacyInfo.xcprivacy. It comes ' +
        'from `ios.privacyManifests` in app.json; Apple rejects builds without it.',
    );
  }

  const icon = await readFile(
    path.join(
      ios,
      'GrandPrixPicks/Images.xcassets/AppIcon.appiconset/App-Icon-1024x1024@1x.png',
    ),
  ).catch(() => null);
  if (!expo.icon || !icon) {
    problems.push(
      'Prebuild generated no 1024px app icon. Set `icon` in app.json; the ' +
        'file is rendered from the brand mark by ' +
        'apps/web/scripts/render-logo-png.mjs.',
    );
  }
} finally {
  await rm(workDir, { recursive: true, force: true });
}

if (problems.length > 0) {
  console.error(
    'The generated iOS project is missing native config that has bitten before:\n\n' +
      problems.map((problem) => `  - ${problem}`).join('\n'),
  );
  process.exit(1);
}
