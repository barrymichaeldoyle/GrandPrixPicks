/**
 * The native iOS project must agree with app.json.
 *
 * `ios/` is tracked in this repo, so changing `app.json` does not update the
 * native asset catalog. Nothing fails when they disagree: the build succeeds
 * and the app ships with whatever was committed. That is not hypothetical.
 * `app.json` had no icon at all for months while the catalog held Expo's blank
 * placeholder, and the first sign anyone would have had was a white square on
 * the App Store listing.
 *
 * So the disagreement is made loud here instead. This checks the icon and the
 * Info.plist keys that app.json claims to own; `UIUserInterfaceStyle` had
 * drifted to Light against a dark-only app, which left every native surface
 * (alerts, keyboard, in-app browser) rendering light.
 *
 * It is deliberately not a full prebuild diff. Regenerating the project to
 * compare would discard the hand-maintained parts of ios/, so this pins the
 * specific keys that have a stated source of truth in app.json.
 *
 * Run from apps/mobile:
 *   node scripts/check-native-assets.mjs
 */
import { readFile } from 'node:fs/promises';
import path from 'node:path';
import process from 'node:process';

const APP_ROOT = path.resolve(import.meta.dirname, '..');

/** Generated by apps/web/scripts/render-logo-png.mjs, from the shared mark. */
const GENERATED_ICON = path.join(APP_ROOT, 'assets', 'icon.png');
const NATIVE_ICON = path.join(
  APP_ROOT,
  'ios',
  'GrandPrixPicks',
  'Images.xcassets',
  'AppIcon.appiconset',
  'App-Icon-1024x1024@1x.png',
);

async function read(file) {
  try {
    return await readFile(file);
  } catch {
    return null;
  }
}

const [generated, native] = await Promise.all([
  read(GENERATED_ICON),
  read(NATIVE_ICON),
]);

if (!generated) {
  console.error(
    'Missing assets/icon.png. Regenerate it from the brand mark:\n' +
      '  pnpm --filter @grandprixpicks/web exec node scripts/render-logo-png.mjs',
  );
  process.exit(1);
}

if (!native) {
  console.error(
    `Missing ${path.relative(APP_ROOT, NATIVE_ICON)}.\n` +
      'Run `npx expo prebuild --platform ios` to regenerate the native project.',
  );
  process.exit(1);
}

const APP_JSON = path.join(APP_ROOT, 'app.json');
const INFO_PLIST = path.join(APP_ROOT, 'ios', 'GrandPrixPicks', 'Info.plist');

/**
 * app.json key -> how the same fact is spelled in Info.plist. Expo title-cases
 * the interface style, so the mapping is explicit rather than inferred.
 */
const PLIST_EXPECTATIONS = [
  {
    appJson: (expo) => expo.userInterfaceStyle,
    plistKey: 'UIUserInterfaceStyle',
    toPlist: (value) => value.charAt(0).toUpperCase() + value.slice(1),
  },
  {
    appJson: (expo) => expo.ios?.bundleIdentifier,
    plistKey: 'CFBundleURLSchemes',
    // The bundle id is one of the registered URL schemes, not a scalar key.
    read: (plist) => {
      const match =
        /<key>CFBundleURLSchemes<\/key>\s*<array>([\s\S]*?)<\/array>/.exec(
          plist,
        );
      return match
        ? [...match[1].matchAll(/<string>(.*?)<\/string>/g)].map((m) => m[1])
        : [];
    },
    compare: (schemes, expected) => schemes.includes(expected),
    describe: (schemes) => schemes.join(', ') || '(none)',
  },
  {
    appJson: (expo) => expo.version,
    plistKey: 'CFBundleShortVersionString',
    toPlist: (value) => value,
  },
];

const PBXPROJ = path.join(
  APP_ROOT,
  'ios',
  'GrandPrixPicks.xcodeproj',
  'project.pbxproj',
);

const [appJsonRaw, plistRaw, pbxproj] = await Promise.all([
  readFile(APP_JSON, 'utf8'),
  readFile(INFO_PLIST, 'utf8'),
  readFile(PBXPROJ, 'utf8'),
]);
const { expo } = JSON.parse(appJsonRaw);

function readScalar(plist, key) {
  const match = new RegExp(`<key>${key}</key>\\s*<string>(.*?)</string>`).exec(
    plist,
  );
  return match?.[1];
}

const drift = [];
for (const check of PLIST_EXPECTATIONS) {
  const declared = check.appJson(expo);
  if (declared === undefined) {
    continue;
  }
  const actual = check.read
    ? check.read(plistRaw)
    : readScalar(plistRaw, check.plistKey);
  const expected = check.toPlist ? check.toPlist(declared) : declared;
  const ok = check.compare
    ? check.compare(actual, expected)
    : actual === expected;
  if (!ok) {
    drift.push(
      `  ${check.plistKey}: app.json implies ${JSON.stringify(expected)}, ` +
        `Info.plist has ${JSON.stringify(check.describe ? check.describe(actual) : actual)}`,
    );
  }
}

if (drift.length > 0) {
  console.error(
    'The native Info.plist disagrees with app.json:\n\n' +
      drift.join('\n') +
      '\n\nThe native file is what actually ships. Sync it with\n' +
      '`npx expo prebuild --platform ios`, or edit Info.plist to match.',
  );
  process.exit(1);
}

/**
 * Push environment, per build configuration.
 *
 * Both configurations pointed at the same entitlements file, which asks for
 * the development APNs gateway. A store build made from that registers sandbox
 * tokens against the production gateway, so every notification fails to
 * deliver and nothing says so: the build succeeds, the app installs, and push
 * is simply dead. `ios/` is committed, so no prebuild will correct it either.
 *
 * expo-doctor's app-config check is switched off for this project because it
 * cannot be satisfied while ios/ is tracked. This is the part of it that
 * actually matters, enforced instead of advised.
 */
const ENTITLEMENTS = [
  { config: 'Debug', file: 'GrandPrixPicks.entitlements', aps: 'development' },
  {
    config: 'Release',
    file: 'GrandPrixPicksRelease.entitlements',
    aps: 'production',
  },
];

const apsDrift = [];
for (const { config, file, aps } of ENTITLEMENTS) {
  const entitlementsPath = path.join(APP_ROOT, 'ios', 'GrandPrixPicks', file);
  const raw = await readFile(entitlementsPath, 'utf8').catch(() => null);
  if (raw === null) {
    apsDrift.push(`  ${config}: missing ${file}`);
    continue;
  }
  const actual = readScalar(raw, 'aps-environment');
  if (actual !== aps) {
    apsDrift.push(
      `  ${config}: ${file} has aps-environment ${JSON.stringify(actual)}, expected ${JSON.stringify(aps)}`,
    );
  }

  const referenced = pbxproj.includes(
    `CODE_SIGN_ENTITLEMENTS = GrandPrixPicks/${file};`,
  );
  if (!referenced) {
    apsDrift.push(`  ${config}: project.pbxproj does not reference ${file}`);
  }
}

if (apsDrift.length > 0) {
  console.error(
    'Push entitlements are wrong for the build configuration:\n\n' +
      apsDrift.join('\n') +
      '\n\nA Release build with aps-environment development registers sandbox\n' +
      'push tokens, and every notification silently fails in production.',
  );
  process.exit(1);
}

if (!generated.equals(native)) {
  console.error(
    'The iOS app icon does not match the generated brand mark.\n\n' +
      `  generated: ${path.relative(APP_ROOT, GENERATED_ICON)} (${generated.length} bytes)\n` +
      `  native:    ${path.relative(APP_ROOT, NATIVE_ICON)} (${native.length} bytes)\n\n` +
      'The native catalog is what actually ships. Sync it with\n' +
      '`npx expo prebuild --platform ios`, or copy the generated file over it.',
  );
  process.exit(1);
}

process.exit(0);
